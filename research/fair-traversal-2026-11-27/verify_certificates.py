"""Exact, solver-independent audit of fair-path certificates.

Usage: python verify_certificates.py certificates.jsonl.gz

Only the Python standard library is used. For each finite graph, this checks:
simple edges; graph automorphisms; vertex transitivity; genuine edge orbits;
Hamilton paths; nonnegative rational probabilities; and uniform edge marginals
after averaging over the finite group generated by the supplied permutations.

The mathematical averaging justification is Theorem 2.1 in structural-results.md.
This is an exact computational certificate audit, not a Lean kernel proof.
"""
import argparse
from collections import Counter
from fractions import Fraction
import gzip
import json

if not __debug__:
    raise RuntimeError('Run this verifier without Python -O: assertions are required.')


def verify(record):
    n = record['n']
    assert isinstance(n, int) and n >= 2
    edges = [tuple(e) for e in record['edges']]
    assert edges and len(set(edges)) == len(edges)
    assert all(0 <= u < v < n for u, v in edges)
    pos = {e: i for i, e in enumerate(edges)}
    generators = record['generators']
    assert generators
    parent = list(range(len(edges)))

    def find(a):
        while a != parent[a]:
            parent[a] = parent[parent[a]]
            a = parent[a]
        return a

    def union(a, b):
        a, b = find(a), find(b)
        if a != b:
            parent[b] = a

    for g in generators:
        assert sorted(g) == list(range(n))
        for i, (u, v) in enumerate(edges):
            image = tuple(sorted((g[u], g[v])))
            assert image in pos
            union(i, pos[image])

    # In a finite permutation group, the monoid generated by permutations also
    # contains their inverses. A forward reachability check therefore suffices.
    seen, todo = {0}, [0]
    while todo:
        u = todo.pop()
        for g in generators:
            if g[u] not in seen:
                seen.add(g[u])
                todo.append(g[u])
    assert len(seen) == n

    roots = sorted({find(i) for i in range(len(edges))})
    labels = {r: j for j, r in enumerate(roots)}
    orbit = [labels[find(i)] for i in range(len(edges))]
    sizes = Counter(orbit)

    paths = record['paths']
    weights = [Fraction(x) for x in record['weights']]
    assert len(paths) == len(weights) and paths
    assert all(w >= 0 for w in weights) and sum(weights) == 1
    expectation = [Fraction(0) for _ in roots]
    for path, weight in zip(paths, weights):
        assert sorted(path) == list(range(n))
        for u, v in zip(path, path[1:]):
            edge = tuple(sorted((u, v)))
            assert edge in pos
            expectation[orbit[pos[edge]]] += weight
    marginal = Fraction(n - 1, len(edges))
    assert all(expectation[j] == marginal * sizes[j] for j in range(len(roots)))
    return len(roots)


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('file')
    args = parser.parse_args()
    op = gzip.open if args.file.endswith('.gz') else open
    total = 0
    families = Counter()
    max_n = 0
    max_orbits = 0
    ids = set()
    with op(args.file, 'rt') as f:
        for line in f:
            if not line.strip():
                continue
            record = json.loads(line)
            try:
                orbits = verify(record)
            except Exception as e:
                raise AssertionError(f"Invalid certificate: {record.get('id')}") from e
            assert record['id'] not in ids, f"Duplicate identifier: {record['id']}"
            ids.add(record['id'])
            total += 1
            families[record['family']] += 1
            max_n = max(max_n, record['n'])
            max_orbits = max(max_orbits, orbits)
    print(json.dumps({'exactly_verified_instances': total,
                      'by_family': dict(sorted(families.items())),
                      'max_vertices': max_n, 'max_edge_orbits': max_orbits,
                      'isomorphism_deduplicated': False,
                      'scope': 'Individual finite cases, not the general conjecture.'}, indent=2))


if __name__ == '__main__':
    main()
